#!/usr/bin/env node
// Builds src/lib/questions/coverage.ts — how many questions exist for each
// topic at each year level, and nothing else.
//
// The practice builder needs to know which subjects, year levels and topics have
// content so it can grey out empty combinations and size the pool. It used to
// answer those questions by importing QUESTION_BANK directly, which meant the
// entire bank — every question, every correct_index, every explanation — was
// bundled into the browser JS for a public page. This map carries the same
// information in a couple of kilobytes and gives away nothing.
//
// Safe to re-run whenever bank.ts changes. Usage: node scripts/gen-coverage.mjs

import { readFileSync, writeFileSync, unlinkSync } from 'fs'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(__dirname, '..')
const bankPath = join(repoRoot, 'src/lib/questions/bank.ts')
const outPath = join(repoRoot, 'src/lib/questions/coverage.ts')

const src = readFileSync(bankPath, 'utf8')
const jsSrc = src
  .replace(/^import type .+\n/m, '')
  .replace(/^type BankQuestion =[\s\S]*?\n\n/m, '')
  .replace(/const (\w+): BankQuestion\[\] = \[/g, 'const $1 = [')
const tmpPath = join(repoRoot, '.bank-tmp3.mjs')
writeFileSync(tmpPath, jsSrc)
const { QUESTION_BANK } = await import('file://' + tmpPath)
unlinkSync(tmpPath)

/** topic -> year level -> how many questions exist */
const coverage = {}
for (const q of QUESTION_BANK) {
  ;(coverage[q.topic] ??= {})[q.year_level] = (coverage[q.topic]?.[q.year_level] ?? 0) + 1
}

const body = Object.keys(coverage)
  .sort()
  .map((topic) => {
    const years = Object.keys(coverage[topic])
      .sort()
      .map((y) => `${y}: ${coverage[topic][y]}`)
      .join(', ')
    return `  ${topic}: { ${years} },`
  })
  .join('\n')

const ts = `// ─────────────────────────────────────────────────────────────────────────────
// Auto-generated by scripts/gen-coverage.mjs — do not hand-edit.
// Regenerate after bank.ts changes with: npm run gen
//
// How many questions exist for each topic at each year level. This is the ONLY
// question-bank-derived data that may be imported by a client component: it
// tells the practice builder which combinations have content without shipping
// any question text, answers or explanations to the browser. Actual questions
// are served by /api/practice/quiz, which returns only the handful selected for
// one quiz.
// ─────────────────────────────────────────────────────────────────────────────

import type { TopicSlug, YearLevel } from '@/types'

export type TopicCoverage = Partial<Record<TopicSlug, Partial<Record<YearLevel, number>>>>

export const TOPIC_COVERAGE: TopicCoverage = {
${body}
}

/** Total questions available for a topic, across every year level. */
export function topicTotal(topic: TopicSlug): number {
  return Object.values(TOPIC_COVERAGE[topic] ?? {}).reduce((a, b) => a + b, 0)
}

/** Questions available for a topic at one year level. */
export function topicCountAt(topic: TopicSlug, yearLevel: YearLevel): number {
  return TOPIC_COVERAGE[topic]?.[yearLevel] ?? 0
}
`

writeFileSync(outPath, ts)
const topics = Object.keys(coverage).length
const total = QUESTION_BANK.length
console.log(`Wrote src/lib/questions/coverage.ts (${topics} topics, ${total} questions summarised).`)
