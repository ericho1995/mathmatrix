// ─── Pedigree charts, drawn as figures ───────────────────────────────────────
// Squares are males and circles females; shaded symbols are affected. Each
// person's number is printed under their symbol. Coordinates are y-up.
const H = 6 // half the width of a symbol
function pedigree(width, height, people, couples, families) {
  const at = Object.fromEntries(people.map(p => [p.id, p]))
  const points = []
  const polygons = []
  const circles = []
  const segments = []
  const texts = []
  for (const p of people) {
    if (p.sex === 'm') {
      const ids = ['a', 'b', 'c', 'd'].map(k => `${p.id}${k}`)
      points.push(
        { id: ids[0], x: p.x - H, y: p.y - H },
        { id: ids[1], x: p.x + H, y: p.y - H },
        { id: ids[2], x: p.x + H, y: p.y + H },
        { id: ids[3], x: p.x - H, y: p.y + H },
      )
      polygons.push(p.affected ? { points: ids, shade: 3 } : { points: ids })
    } else {
      points.push({ id: `${p.id}o`, x: p.x, y: p.y })
      circles.push(p.affected ? { center: `${p.id}o`, r: H, shade: 3 } : { center: `${p.id}o`, r: H })
    }
    texts.push({ x: p.x, y: p.y - H - 6, text: p.id })
  }
  for (const [a, b] of couples) {
    points.push({ id: `${a}R`, x: at[a].x + H, y: at[a].y }, { id: `${b}L`, x: at[b].x - H, y: at[b].y })
    segments.push({ from: `${a}R`, to: `${b}L` })
  }
  for (const { parents: [a, b], children, sibY } of families) {
    const mx = (at[a].x + at[b].x) / 2
    points.push({ id: `${a}${b}m`, x: mx, y: at[a].y }, { id: `${a}${b}s`, x: mx, y: sibY })
    segments.push({ from: `${a}${b}m`, to: `${a}${b}s` })
    const xs = children.map(c => at[c].x)
    for (const c of children) {
      points.push({ id: `${c}S`, x: at[c].x, y: sibY }, { id: `${c}T`, x: at[c].x, y: at[c].y + H })
      segments.push({ from: `${c}S`, to: `${c}T` })
    }
    const left = children[xs.indexOf(Math.min(...xs))]
    const right = children[xs.indexOf(Math.max(...xs))]
    segments.push({ from: `${left}S`, to: `${right}S` })
  }
  return { kind: 'figure', width, height, points, polygons, circles, segments, texts }
}

